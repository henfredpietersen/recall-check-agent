  function hostOf(url) { try { return new URL(url).hostname; } catch (e) { return ""; } }

  function loadScript(src) {
    return new Promise(function (res, rej) {
      if (window.loadPyodide) return res();
      var s = document.createElement("script");
      s.src = src; s.onload = res; s.onerror = function () { rej(new Error("couldn't download the Python runtime")); };
      document.head.appendChild(s);
    });
  }

  function traceLine(n, html) {
    $("#trace").insertAdjacentHTML("beforeend", "<div class='t'><span class='i'>" + n + "</span><span>" + html + "</span></div>");
  }

  function understood(u) {
    if (!u) return "";
    if (u.intent === "products") return "a product list: " + u.lines.length + " line" + (u.lines.length === 1 ? "" : "s") + (u.truncated ? " (first 200 only)" : "") + ", recalls since " + esc(u.since);
    if (u.intent === "vehicle") return "a vehicle: " + esc(u.year) + " " + esc(u.make) + " " + esc(u.model);
    if (u.intent === "vin") return "a VIN: <code>" + esc(u.vin) + "</code>";
    return "";
  }

  function renderProducts(a) {
    var rows = a.results.map(function (r) {
      var pill = r.verdict === "recalled" ? "<span class='pill bad'>recalled</span>" : r.verdict === "check" ? "<span class='pill warn'>check</span>" : "<span class='pill dimc'>no match</span>";
      var detail = r.recall ? "<div class='d'>" + esc(r.recall.title) + " (" + esc(r.recall.date) + "). Matched on " + esc(r.reasons.join(", ")) + ". " +
        (r.recall.hazard ? "Hazard: " + esc(r.recall.hazard) + " " : "") +
        (r.recall.url ? "<a href='" + esc(r.recall.url) + "' target='_blank' rel='noopener'>Recall notice</a>" : "") + "</div>" : "";
      return "<div class='item'>" + pill + " <b>" + esc(r.line) + "</b>" + detail + "</div>";
    }).join("");
    return "<p class='big'>" + esc(a.text) + "</p>" + rows + "<p style='margin-top:12px;font-size:.84rem'>" + esc(a.caveat) + "</p>";
  }

  function renderVehicle(a) {
    var rows = a.recalls.map(function (r) {
      var warn = r.do_not_drive ? " <span class='pill bad'>do not drive</span>" : r.park_outside ? " <span class='pill warn'>park outside</span>" : "";
      return "<div class='item'><b>" + esc(r.component) + "</b>" + warn + " <span class='dimc'>· campaign " + esc(r.campaign) + ", " + esc(r.date) + "</span>" +
        "<div class='d'>" + esc(r.summary) + "</div>" + (r.remedy ? "<div class='d'><b>Fix:</b> " + esc(r.remedy) + "</div>" : "") + "</div>";
    }).join("");
    var more = a.recalls.length > 6 ? "<p style='font-size:.84rem'>Showing all " + a.recalls.length + ", urgent ones first.</p>" : "";
    return "<p class='big'>" + esc(a.text) + "</p>" + more + rows + "<p style='margin-top:12px;font-size:.84rem'>" + esc(a.caveat) + "</p>";
  }

  function run() {
    if (busy || !py) return;
    var text = $("#txt").value;
    busy = true; $("#run").disabled = true;
    $("#trace").innerHTML = "<div class='trace'><h3>What the agent did</h3></div>";
    $("#ans").innerHTML = "";
    var obs = [], n = 0;
    function next() {
      py.globals.set("_req", text);
      py.globals.set("_obs", JSON.stringify(obs));
      py.globals.set("_today", today());
      var s = JSON.parse(py.runPython("agent.step_json(_req, _obs, _today)"));
      if (n === 0 && s.understood) traceLine("→", "Read this as " + understood(s.understood) + ".");
      if (s.action === "call") {
        n += 1;
        if (HOSTS.indexOf(hostOf(s.url)) < 0) { traceLine("!", "<span class='bad'>Refused a call to " + esc(hostOf(s.url)) + "</span>"); return done(); }
        traceLine(n, "<b>" + esc(TOOLS[s.tool] || s.tool) + "</b>: " + esc(s.why) + " <span class='w'>(" + esc(hostOf(s.url)) + ")</span> <span id='w" + n + "' class='dimc'>…</span>");
        var t0 = performance.now(), my = n;
        return fetch(s.url).then(function (r) {
          if (!r.ok) throw new Error(hostOf(s.url) + " returned " + r.status);
          return r.json();
        }).then(function (data) {
          var count = Array.isArray(data) ? data.length + " records" : (data.Count != null ? data.Count + " results" : "ok");
          $("#w" + my).textContent = count + ", " + ((performance.now() - t0) / 1000).toFixed(1) + " s";
          obs.push({ tool: s.tool, args: s.args, data: data });
          return next();
        }).catch(function (e) {
          $("#w" + my).innerHTML = "<span class='bad'>failed</span>";
          $("#ans").innerHTML = "<div class='ans'><p class='big'>The " + esc(TOOLS[s.tool] || s.tool) + " service didn't answer (" + esc(e.message) + ").</p><p>So there's no answer, rather than a guess. Try again in a minute.</p></div>";
          done();
        });
      }
      if (s.action === "ask") {
        traceLine("?", "Stopped to ask instead of guessing.");
        $("#ans").innerHTML = "<div class='ans'><p class='big'>" + esc(s.question) + "</p>" + (s.note ? "<p>" + esc(s.note) + "</p>" : "") + "</div>";
      } else if (s.action === "stop") {
        traceLine("■", "Stopped.");
        $("#ans").innerHTML = "<div class='ans'><p class='big'>" + esc(s.reason) + "</p></div>";
      } else if (s.action === "done") {
        traceLine("✓", "Answered after " + n + " call" + (n === 1 ? "" : "s") + ".");
        $("#ans").innerHTML = "<div class='ans'>" + (s.answer.kind === "products" ? renderProducts(s.answer) : renderVehicle(s.answer)) + "</div>";
      }
      done();
    }
    function done() { busy = false; $("#run").disabled = false; }
    try { next(); } catch (e) { $("#ans").innerHTML = "<div class='ans'><p class='big'>Something went wrong: " + esc(e.message) + "</p></div>"; done(); }
  }

